-- Daily Kharcha RLS verification checklist
-- Run only in a disposable Supabase test project with at least two test companies.
-- Do not run against real customer data. These are manual test cases, not a substitute
-- for automated pgTAP tests or a professional security review.

-- Test identities:
--   owner: a user_id present in public.platform_owners
--   admin_a / employee_a: profiles.company_id = company A
--   admin_b / employee_b: profiles.company_id = company B

-- 1. As employee_a, SELECT from expenses must return only own expenses.
-- 2. As employee_a, SELECT from profiles must return only own profile.
-- 3. As admin_a, SELECT from profiles/expenses must return company A only.
-- 4. As admin_a, SELECT from companies must return company A only.
-- 5. As admin_a, SELECT/UPDATE company B records must affect zero rows / be denied.
-- 6. As employee_a, inserting an expense with employee_id=employee_b must be denied.
-- 7. As employee_a, changing a profile role or company_id must be denied.
-- 8. As HR, salary_records must not be readable or writable under current policies.
-- 9. As employee_a, salary_records should expose only own row if that employee self-view
--    is enabled by product policy; otherwise remove employee salary read access.
-- 10. As non-owner, calling review_company_application must fail with permission denied.
-- 11. As owner, approving a pending application must create exactly one company and
--     exactly one first-admin profile; a second approval attempt must fail.
-- 12. Rejected applications must not create a company or profile.
-- 13. Receipt/sample storage must be private and enforce the same company boundary.
-- 14. Confirm audit events cannot be forged by clients and revisions are generated by
--     trusted database triggers before production use.

